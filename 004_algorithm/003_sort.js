/**
 *  2.2.1 バブルソート
 *
 *  バブルソートを実装してください。(入力は数値のみ)
 *
 *  example:
 *    [1, 3, 2, 4, 5] => [1, 2, 3, 4, 5]
 *    [5, 3, 2, 1] => [1, 2, 3, 5]
 */

function bubbleSort(array) {
  let temp;
  for (let i = 0; i < array.length; i++) {
    for (let j = i + 1; j < array.length; j++) {
      if (array[i] > array[j]) {
        temp = array[i];
        array[i] = array[j];
        array[j] = temp;
      }
    }
  }
  return array;
}

/**
 *  2.2.2 挿入ソート
 *
 *  挿入ソートを実装してください。(入力は数値のみ)
 *
 *  example:
 *    [1, 3, 2, 4, 5] => [1, 2, 3, 4, 5]
 *    [5, 3, 2, 1] => [1, 2, 3, 5]
 */

function insertSort(array) {
  let temp, j; // 挿入する値と比較に使うインデックス用の変数
  for (let i = 1; i < array.length; i++) {
    // 配列の2番目の要素（index 1）からループ
    temp = array[i]; // 挿入対象の値を一時的に保存
    j = i - 1; // i の1つ前の要素を j に設定
    while (j >= 0 && array[j] > temp) {
      // j が 0 以上で、array[j] が temp より大きい間
      array[j + 1] = array[j]; // 右に1つ移動
      j--; // j をデクリメント（左に移動）
    }
    array[j + 1] = temp; // 空いた位置に temp を挿入
  }
  return array;
}

